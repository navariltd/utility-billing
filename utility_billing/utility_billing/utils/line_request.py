"""Find the Utility Service Request of each Sales Invoice line, under Item Price.

A new invoice carries the request on its lines (``Sales Invoice Item.utility_service_request``),
so one invoice may bill lines of several submitted requests of its customer. An
old invoice carries it on its header only. Readers take the line's request when
set, else the header's, so the two never apply to the same invoice.

A governed line (a utility item that is not priced from a Meter Reading) gets
its request this way:

* With a property, the rent line of a property or a secondary item whose
  property was picked: the request of the customer leasing that property on the
  line's billing date and listing the item. A row released on the request, or
  on a Contract of the request that is not cancelled, leases nothing.
* A secondary item without a property is an ordinary line: no request, no
  property, and the cost center the user or ERPNext gave it.

The rate of a line is checked against the request found here; it never chooses
one. Drafts generated by Auto Repeat from an invoice linked through its header
keep the header and are governed as before.
"""

import frappe
from frappe import _
from frappe.query_builder.functions import Coalesce
from frappe.utils import cint, getdate
from pypika.functions import NullIf

from utility_billing.utility_billing.utils.release import contract_releases, owns
from utility_billing.utility_billing.utils.utility_item_classifier import (
	USR_DOCTYPE,
	USR_ITEM_DOCTYPE,
	USR_PROPERTY_DOCTYPE,
	get_utility_items,
)

REQUEST_FIELD = "utility_service_request"
POSTING_DATE_FIELD = "custom_posting_date"

RESOLVED = "resolved"
PICK_REQUEST = "pick_request"
PICK_PROPERTY = "pick_property"
ORDINARY = "ordinary"
NOT_COVERED = "not_covered"
NOT_LISTED = "not_listed"


def line_requests_stored() -> bool:
	"""Return whether invoice lines store their request yet.

	The column comes with the migrate that syncs the line field. Until then,
	queries read the header only, as before.
	"""
	return frappe.db.has_column("Sales Invoice Item", REQUEST_FIELD)


def request_of_line(line, invoice):
	"""Return the query term for the request of an invoice line: its own, else its invoice's.

	Args:
		line: ``Sales Invoice Item`` table of the query.
		invoice: ``Sales Invoice`` table of the query.
	"""
	if not line_requests_stored():
		return invoice[REQUEST_FIELD]

	return Coalesce(NullIf(line[REQUEST_FIELD], ""), invoice[REQUEST_FIELD])


def invoice_requests(service_requests) -> list[tuple[str, str]]:
	"""Return the ``(invoice, request)`` pairs of the Sales Invoices of some requests.

	An invoice belongs to each request its lines carry, else to its header's,
	so one billing lines of two requests is returned for both.
	"""
	names = [name for name in service_requests or () if name]
	if not names:
		return []

	invoice = frappe.qb.DocType("Sales Invoice")
	line = frappe.qb.DocType("Sales Invoice Item")
	request = request_of_line(line, invoice)

	return (
		frappe.qb.from_(line)
		.join(invoice)
		.on(line.parent == invoice.name)
		.select(invoice.name, request.as_("service_request"))
		.distinct()
		.where(line.parenttype == "Sales Invoice")
		.where(request.isin(names))
	).run()


def line_request(doc, row) -> str | None:
	"""Return the request of an invoice line: its own, else its invoice's."""
	return row.get(REQUEST_FIELD) or doc.get(REQUEST_FIELD)


def billing_date(doc, row):
	return getdate(row.get(POSTING_DATE_FIELD) or doc.posting_date)


def uses_header_path(doc) -> bool:
	"""Return whether a draft keeps its header request: one generated by Auto Repeat from an old invoice."""
	return bool(doc.get("auto_repeat") and doc.get(REQUEST_FIELD))


def get_governed_rows(doc) -> list:
	"""Return the lines billing a utility item, except those priced from a Meter Reading."""
	rows = [row for row in doc.get("items") or [] if row.item_code and not row.get("meter_reading")]
	utility_items = get_utility_items(row.item_code for row in rows)

	return [row for row in rows if row.item_code in utility_items]


def move_header_to_lines(doc, rows) -> None:
	"""Move the header request of a draft onto its governed lines without one, and clear the header.

	A secondary line without a property takes the request's property when it
	has exactly one, so the line is found again by its property.
	"""
	header = doc.get(REQUEST_FIELD)
	if not header:
		return

	for row in rows:
		if not row.get(REQUEST_FIELD):
			row.set(REQUEST_FIELD, header)
			fill_single_property(row, header)

	doc.set(REQUEST_FIELD, None)


def fill_single_property(row, service_request: str) -> None:
	"""Give a line without a property the property of its request, when the request has exactly one."""
	if row.get("utility_property"):
		return

	properties = request_properties(service_request)
	if len(properties) == 1:
		row.utility_property = properties[0]


def request_properties(service_request: str) -> list[str]:
	return sorted(
		set(
			frappe.get_all(
				USR_PROPERTY_DOCTYPE,
				filters={"parent": service_request, "parenttype": USR_DOCTYPE, "utility_property": ("is", "set")},
				pluck="utility_property",
			)
		)
	)


class RequestIndex:
	"""The submitted requests of one customer listing the items of one invoice, read once."""

	def __init__(self, customer: str, item_codes):
		self.customer = customer
		codes = sorted({code for code in item_codes if code})
		self.listing = self._requests_by_item(codes)
		names = sorted(set().union(*self.listing.values())) if self.listing else []
		self.headers = {
			row.name: row
			for row in frappe.get_all(
				USR_DOCTYPE, filters={"name": ("in", names or [""])}, fields=["name", "start_date", "end_date"]
			)
		}
		self.leases = self._leases(names)
		self.released = contract_releases(names)
		self.owners = self._owners(codes)

	def _requests_by_item(self, codes) -> dict[str, set[str]]:
		listing = {code: set() for code in codes}
		if not (self.customer and codes):
			return listing

		request = frappe.qb.DocType(USR_DOCTYPE)
		row = frappe.qb.DocType(USR_ITEM_DOCTYPE)
		rows = (
			frappe.qb.from_(row)
			.join(request)
			.on(row.parent == request.name)
			.select(row.item_code, request.name.as_("service_request"))
			.where(row.parenttype == USR_DOCTYPE)
			.where(request.docstatus == 1)
			.where(request.customer == self.customer)
			.where(row.item_code.isin(codes))
		).run(as_dict=True)
		for entry in rows:
			listing[entry.item_code].add(entry.service_request)

		return listing

	def _leases(self, names) -> dict[str, list]:
		leases = {name: [] for name in names}
		if not names:
			return leases

		for row in frappe.get_all(
			USR_PROPERTY_DOCTYPE,
			filters={"parent": ("in", names), "parenttype": USR_DOCTYPE, "utility_property": ("is", "set")},
			fields=["parent", "utility_property", "start_date", "end_date", "is_active"],
			order_by="idx asc",
		):
			leases[row.parent].append(row)

		return leases

	def _owners(self, codes) -> dict[str, list[str]]:
		owners = {code: [] for code in codes}
		if not codes:
			return owners

		for row in frappe.get_all(
			"Utility Property", filters={"service_item": ("in", codes)}, fields=["name", "service_item"], order_by="name"
		):
			owners[row.service_item].append(row.name)

		return owners

	def leases_property(self, service_request: str, property_name: str, date) -> bool:
		"""Return whether a request leases a property on a date.

		A row released on the Contract leases up to and including its Released
		On; without one, and a row released on the request, it leases nothing.
		"""
		key = (service_request, property_name)
		header = self.headers[service_request]
		for row in self.leases.get(service_request) or []:
			if row.utility_property != property_name or cint(row.is_active) == 0:
				continue
			if owns(
				row.start_date or header.start_date,
				row.end_date or header.end_date,
				date,
				key in self.released,
				self.released.get(key),
			):
				return True

		return False

	def properties_leased(self, service_requests, date) -> list[str]:
		"""Return the properties some requests lease on a date, released rows aside."""
		return sorted(
			{
				row.utility_property
				for name in service_requests
				for row in self.leases.get(name) or []
				if self.leases_property(name, row.utility_property, date)
			}
		)


def covers(start, end, date) -> bool:
	"""Return whether ``date`` falls within ``start`` and ``end``; blank bounds are open."""
	if start and date < getdate(start):
		return False

	return not (end and date > getdate(end))


def resolve_line(doc, row, index: RequestIndex) -> frappe._dict:
	"""Return the request of one governed line, or why it has none.

	Returns:
		``status`` (one of the module's statuses), ``service_request`` when
		resolved, ``utility_property`` the line bills (``None`` without one),
		``candidates`` the user may pick from, ``editable`` whether the line's
		request is the user's to pick, ``rent_item`` whether the item is a
		property's rent item, ``property_candidates`` the properties
		of the customer leased on the line's date by a request listing its item,
		and the blocking ``message``. A secondary line without a property is
		``ordinary``: it has no request and is not governed.
	"""
	date = billing_date(doc, row)
	customer = frappe.bold(doc.customer)
	item = frappe.bold(row.item_code)
	result = frappe._dict(
		status=None,
		service_request=None,
		utility_property=None,
		candidates=[],
		editable=False,
		rent_item=False,
		property_candidates=[],
		message=None,
	)

	owners = index.owners.get(row.item_code) or []
	result.rent_item = bool(owners)
	if not owners and not row.get("utility_property"):
		result.status = ORDINARY
		return result

	listing = sorted(index.listing.get(row.item_code) or [])
	if not listing:
		result.status = NOT_LISTED
		result.message = _(
			"Row #{0}: {1} is not on any submitted Utility Service Request of {2}. Add it to one of the "
			"customer's Utility Service Requests, or create one, before billing it."
		).format(row.idx, item, customer)
		return result

	result.property_candidates = index.properties_leased(listing, date)
	on_date = (
		_("On {0}, {1} can be billed for: {2}.").format(
			date, item, ", ".join(frappe.bold(name) for name in result.property_candidates)
		)
		if result.property_candidates
		else _("No property of {0} listing {1} is leased on {2}.").format(customer, item, date)
	)

	property_name = row.get("utility_property")
	if owners and property_name not in owners:
		# The rent item of a property bills that property, whatever the line says
		property_name = owners[0] if len(owners) == 1 else None

	if property_name:
		result.utility_property = property_name
		leasing = [name for name in listing if index.leases_property(name, property_name, date)]
		return _pick(
			result,
			row,
			date,
			leasing,
			_("Row #{0}: No Utility Service Request of {1} leases {2} on {3} and lists {4}. {5}").format(
				row.idx, customer, frappe.bold(property_name), date, item, on_date
			),
		)

	# A rent item of several properties: the line has to say which one
	result.status = PICK_PROPERTY
	result.message = _("Row #{0}: Pick the property on this line. {1} is the rent item of {2}.").format(
		row.idx, item, ", ".join(owners)
	)
	return result


def _pick(result, row, date, candidates: list[str], not_covered: str) -> frappe._dict:
	result.candidates = candidates
	if len(candidates) == 1:
		result.status = RESOLVED
		result.service_request = candidates[0]
	elif row.get(REQUEST_FIELD) in candidates:
		result.status = RESOLVED
		result.service_request = row.get(REQUEST_FIELD)
	elif candidates:
		result.status = PICK_REQUEST
		result.message = _(
			"Row #{0}: Several Utility Service Requests cover {1} on {2}. Pick one in the Utility "
			"Service Request of this line: {3}."
		).format(row.idx, frappe.bold(row.item_code), date, ", ".join(candidates))
	else:
		result.status = NOT_COVERED
		result.message = not_covered

	return result


def resolve_lines(doc, rows) -> dict[str, frappe._dict]:
	"""Return the resolution of each governed line, keyed by line name, else by its row number."""
	index = RequestIndex(doc.customer, [row.item_code for row in rows])
	return {row.name or str(row.idx): resolve_line(doc, row, index) for row in rows}
