"""Comparison tests: what must stay as on develop when requests move to the invoice lines.

Run against develop and against the change; every test must pass on both.
Drafts generated by Auto Repeat from an invoice linked through its header,
meter reading lines and sites billing rent by Auto Repeat are governed exactly
as before. Invoices are unsaved and governed through the hook functions.
"""

import frappe
from frappe.tests.utils import FrappeTestCase

from utility_billing.utility_billing.overrides.server import sales_invoice
from utility_billing.utility_billing.tests import lease_fixtures as fx
from utility_billing.utility_billing.tests.line_request_fixtures import (
	ELECTRICITY,
	P1,
	fingerprint,
	make_invoice,
	make_price,
	make_request,
	setup_items,
)

AUTO_REPEAT = "_Test Line USR Auto Repeat"
METER_READING = "_Test Line USR Meter Reading"


class ComparisonCase(fx.SavepointMixin, FrappeTestCase):
	approach = "Item Price"

	def setUp(self):
		super().setUp()
		fx.use_approach(self.approach)
		setup_items()
		self.u1 = make_request([(P1, "2027-01-01", "2027-12-31")], "2027-01-01", "2028-01-01", [(ELECTRICITY, 200)])
		make_price(P1, 1000, "2027-01-01", "2027-12-31")

	def govern(self, invoice):
		governed = sales_invoice.govern_utility_lines(invoice) if self.approach == "Item Price" else []
		sales_invoice.fill_request_line_dimensions(invoice)
		return governed


class TestAutoRepeatDraftUnchanged(ComparisonCase):
	"""A draft generated by Auto Repeat from an invoice linked through its header."""

	def draft(self, posting_date="2027-03-10"):
		return make_invoice(
			[{"item_code": P1, "rate": 1, "price_list_rate": 1}, {"item_code": ELECTRICITY, "rate": 200}],
			posting_date,
			header=self.u1.name,
			auto_repeat=AUTO_REPEAT,
		)

	def test_the_header_stays_and_the_lines_carry_no_request(self):
		draft = self.draft()

		governed = self.govern(draft)

		self.assertEqual(
			fingerprint(draft),
			{
				"header": self.u1.name,
				"lines": [
					(P1, P1, None, 1000, 1000, None),
					(ELECTRICITY, None, None, 200, None, None),
				],
			},
		)
		self.assertEqual([entry.utility_property for entry in governed], [P1, None])

	def test_a_wrong_secondary_rate_is_refused_with_the_same_message(self):
		draft = self.draft()
		draft.items[1].rate = 999

		with self.assertRaisesRegex(frappe.ValidationError, "must be .*200.* the rate agreed on Utility Service Request"):
			self.govern(draft)

	def test_a_date_outside_the_lease_is_refused_with_the_same_message(self):
		draft = self.draft(posting_date="2028-03-10")

		with self.assertRaisesRegex(frappe.ValidationError, "(after the lease|not all on the same|Several|does not cover)"):
			self.govern(draft)


	def test_require_contract_checks_the_header_request(self):
		fx.use_approach("Item Price", require_contract=1, require_signed=1)

		with self.assertRaisesRegex(frappe.ValidationError, f"{self.u1.name}</strong> has no signed, submitted Contract"):
			sales_invoice.validate(self.draft())

		fx.make_contract(self.u1.name)
		draft = self.draft()
		sales_invoice.validate(draft)
		self.assertEqual(fingerprint(draft)["header"], self.u1.name)


class TestMeterLinesUnchanged(ComparisonCase):
	def meter_line(self):
		return {"item_code": ELECTRICITY, "rate": 37, "price_list_rate": 37, "meter_reading": METER_READING}

	def test_a_meter_only_invoice_is_left_alone_and_its_header_cleared(self):
		invoice = make_invoice([self.meter_line()], "2027-03-10", header=self.u1.name)

		self.assertEqual(self.govern(invoice), [])

		self.assertEqual(
			fingerprint(invoice),
			{"header": None, "lines": [(ELECTRICITY, None, None, 37, 37, METER_READING)]},
		)

	def test_a_meter_line_beside_a_rent_line_keeps_its_rate_and_no_request(self):
		invoice = make_invoice([self.meter_line(), {"item_code": P1}], "2027-03-10", header=self.u1.name)

		self.govern(invoice)

		self.assertEqual(fingerprint(invoice)["lines"][0], (ELECTRICITY, None, None, 37, 37, METER_READING))
		self.assertEqual(invoice.items[1].rate, 1000)


class TestAutoRepeatSiteUnchanged(ComparisonCase):
	"""A site billing rent by Auto Repeat: nothing is governed, the header is kept."""

	approach = "Auto Repeat"

	def test_lines_and_header_are_left_as_they_are(self):
		invoice = make_invoice(
			[{"item_code": P1, "rate": 5, "price_list_rate": 5}, {"item_code": ELECTRICITY, "rate": 7}],
			"2027-03-10",
			header=self.u1.name,
		)

		sales_invoice.validate(invoice)

		self.assertEqual(
			fingerprint(invoice),
			{
				"header": self.u1.name,
				"lines": [(P1, None, None, 5, 5, None), (ELECTRICITY, None, None, 7, None, None)],
			},
		)
